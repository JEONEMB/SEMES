def _disp_width(ch: str) -> int:
    return 2 if unicodedata.east_asian_width(ch) in ("W", "F") else 1


def wrap(text: str, width: int) -> list[str]:
    """한글(전각)을 2칸으로 세어 줄바꿈한다. textwrap 은 한글 폭을 1칸으로 세서 PDF 칸을 넘는다."""
    lines, cur, cur_w = [], "", 0
    for word in text.split(" "):
        w = sum(_disp_width(c) for c in word)
        if cur and cur_w + 1 + w > width:
            lines.append(cur); cur, cur_w = "   " + word, 3 + w   # 이어지는 줄은 들여쓰기
        else:
            cur, cur_w = (cur + " " + word, cur_w + 1 + w) if cur else (word, w)
    if cur:
        lines.append(cur)
    return lines
